export function readLanguage() {
  try {
    const saved = localStorage.getItem(STORAGE_KEY);
    // 旧バージョンで保存された "zh" は簡体字として扱う
    const code = saved === "zh" ? "zh-CN" : saved;
    return code && dict[code] ? code : "ja";
  } catch {
    return "ja";
  }
}

export function saveLanguage(code) {
  try {
    localStorage.setItem(STORAGE_KEY, code);
  } catch {}
  window.dispatchEvent(new Event(EVENT_NAME));
}

// 現在の表示言語（切り替えるとすぐ反映）
export function useLang() {
  const [lang, setLang] = useState("ja");
  useEffect(() => {
    const update = () => setLang(readLanguage());
    update();
    window.addEventListener(EVENT_NAME, update);
    window.addEventListener("storage", update);
    return () => {
      window.removeEventListener(EVENT_NAME, update);
      window.removeEventListener("storage", update);
    };
  }, []);
  return lang;
}

// t("key", { n: 5 }) の形で文言を取り出す。未翻訳は日本語にそろえる
export function useT() {
  const lang = useLang();
  const t = useCallback(
    (key, vars) => {
      const text = dict[lang]?.[key] ?? dict.ja[key] ?? key;
      return vars
        ? text.replace(/\{(\w+)\}/g, (_, name) => String(vars[name] ?? ""))
        : text;
    },
    [lang]
  );
  return { t, lang };
}
